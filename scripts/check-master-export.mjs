import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { createScene } from '../src/studio/project.ts';
const dir=await mkdtemp(join(tmpdir(),'storystudio-master-'));
const scene=createScene('Synthetic',1,64,64,3);
const art=await readFile(new URL('../public/assets/scene-01-normalized/background.png',import.meta.url));
scene.layers=[{id:'arbitrary-art',name:'Synthetic backplate',asset:`data:image/png;base64,${art.toString('base64')}`,depth:.5}];
scene.tracks=[{id:'move',target:'camera',property:'x',startFrame:0,endFrame:2,startValue:0,endValue:2,easing:'linear',intensity:1,limits:{min:-10,max:10}}];
const config=join(dir,'scene.json'),output=join(dir,'scene.mp4');await writeFile(config,JSON.stringify({config:scene,intensity:1}));
const r=spawnSync(process.execPath,['scripts/export-video.mjs',output,'--config',config],{cwd:new URL('..',import.meta.url),encoding:'utf8',timeout:120000});
assert.equal(r.status,0,`${r.stdout}\n${r.stderr}`);
const manifest=JSON.parse(await readFile(join(dir,'scene-frames','manifest.json'),'utf8'));
assert.equal(manifest.complete,true);assert.equal(manifest.frames.length,3);assert.equal(manifest.checks.repeatedFrame.equal,true);
assert.ok((await readFile(output)).length>0);
const blocked=spawnSync(process.execPath,['scripts/export-video.mjs',output,'--config',config],{cwd:new URL('..',import.meta.url),encoding:'utf8',timeout:30000});
assert.notEqual(blocked.status,0);assert.match(blocked.stderr,/Refusing to overwrite/);
console.log('Master export passed: synthetic 3-frame scene, validated H.264 metadata, and overwrite protection.');
